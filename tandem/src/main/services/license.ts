/**
 * Offline, pay-once licensing.
 *
 * A key looks like:  TANDEM-<base64url(payload json)>.<base64url(ed25519 signature)>
 * payload = { licensee, email?, edition, issuedAt, seats? }
 *
 * The private key never ships; `npm run license:keygen` creates a keypair and prints the
 * public key to paste into PUBLIC_KEY_PEM below. `npm run license:sign` mints keys.
 * Nothing phones home: the buyer downloads the app, pastes the key, done.
 */
import { createPublicKey, verify } from 'node:crypto'
import type { LicenseState, Settings } from '@shared/types'

// Replace with the public half of the keypair generated by scripts/license-keygen.mjs.
// The embedded default is a throwaway development key so the trial/activation flow can be tested.
export const PUBLIC_KEY_PEM =
  process.env.TANDEM_LICENSE_PUBLIC_KEY ??
  `-----BEGIN PUBLIC KEY-----
MCowBQYDK2VwAyEAmLbNdLsK744vJcTmDoq17Hk8jNczhdINJfNvXRJnGC8=
-----END PUBLIC KEY-----`

export const TRIAL_DAYS = 14

export interface LicensePayload {
  licensee: string
  email?: string
  edition: string
  issuedAt: number
  seats?: number
}

function b64urlToBuf(s: string): Buffer {
  const pad = s.length % 4 === 0 ? '' : '='.repeat(4 - (s.length % 4))
  return Buffer.from(s.replace(/-/g, '+').replace(/_/g, '/') + pad, 'base64')
}

export function parseLicenseKey(key: string, publicKeyPem = PUBLIC_KEY_PEM): LicensePayload | null {
  const trimmed = key.trim()
  if (!trimmed.startsWith('TANDEM-')) return null
  const body = trimmed.slice('TANDEM-'.length)
  const dot = body.lastIndexOf('.')
  if (dot === -1) return null
  const payloadB64 = body.slice(0, dot)
  const sigB64 = body.slice(dot + 1)
  try {
    const payloadBuf = b64urlToBuf(payloadB64)
    const sig = b64urlToBuf(sigB64)
    const pub = createPublicKey(publicKeyPem)
    if (!verify(null, payloadBuf, pub, sig)) return null
    const payload = JSON.parse(payloadBuf.toString('utf8')) as LicensePayload
    if (!payload.licensee || !payload.edition || !payload.issuedAt) return null
    return payload
  } catch {
    return null
  }
}

export function evaluateLicense(settings: Settings, nowMs = Date.now()): LicenseState {
  if (settings.licenseKey) {
    const p = parseLicenseKey(settings.licenseKey)
    if (p) return { status: 'licensed', licensee: p.licensee, edition: p.edition, issuedAt: p.issuedAt }
    return { status: 'invalid', message: 'The license key is not valid for this build.' }
  }
  const started = settings.trialStartedAt ?? nowMs
  const elapsedDays = (nowMs - started) / 86_400_000
  const left = Math.ceil(TRIAL_DAYS - elapsedDays)
  if (left > 0) return { status: 'trial', trialDaysLeft: left }
  return { status: 'expired', trialDaysLeft: 0, message: 'Your trial has ended. Enter a license key to keep using Tandem.' }
}
